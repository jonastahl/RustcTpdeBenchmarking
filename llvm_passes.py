"""Measures which LLVM IR passes of the O1 pipeline bring which improvements in compile time and runtime.

All variants keep opt-level=0 for the LLVM backend (FastISel + fast register allocator), since TPDE has no
SelectionDAG or greedy register allocator either. On top of the O0 pipeline, every variant runs its own pass pipeline
(-Cpasses). Only the full O1 reference also switches the backend to O1.

The variants are rustc wrapper scripts generated into llvm_passes/variants, which append the flags of the variant to
every rustc invocation. The collector skips benchmarks that already have results, so an aborted run continues where it
stopped. --rerun measures everything again, together with --only just the given variants."""
import argparse
import shlex
import shutil
from pathlib import Path

from src.benchmarks import compiletime_results, run_compiletime_benchmark, run_runtime_benchmark, runtime_results
from src.helper import TMP_DIR, run_task

ROOT = Path(__file__).resolve().parent
OUT_DIR = ROOT / "llvm_passes"
VARIANT_DIR = OUT_DIR / "variants"
TOOLCHAIN = "+nightly-2026-08-19"
TARGET = "x86_64-unknown-linux-gnu"

# Compile time benchmarks (names of deps/rustc-perf/collector/compile-benchmarks)
COMPILE_BENCHMARKS = ["cranelift-codegen-0.119.0"]
COMPILE_ITERATIONS = 5

# Runtime benchmarks per group (directory in deps/rustc-perf/collector/runtime-benchmarks), only these are built
RUNTIME_BENCHMARKS = {
    "nbody": ["nbody_5k"],
    "hashmap": ["hashmap_find_1m"],
    "parsing": ["nom-json"],
}
RUNTIME_ITERATIONS = 5

# Result databases, relative to deps/rustc-perf
DB_DIR = ROOT / "deps/rustc-perf"
COMPILE_DB = "llvm_passes.db"
RUNTIME_DB = "llvm_passes_runtime.db"

# All other variants are shown relative to this one
BASELINE = "O0"

# The pipeline O1 runs, printed with --print-pipeline. The variants below take their pass parameters from it.
PIPELINE_LEVEL = "O1"

# Each variant: (name, pipeline for -Cpasses or None, further rustc flags, cargo profile settings).
# The pipeline runs after rustc's O0 pipeline (only always-inline) and uses the syntax of `opt -passes=`.
VARIANTS = [
    # References
    ("O0", None, [], []),
    ("O1", None, [], ["opt-level=1"]),
    # The whole O1 IR pipeline, but with the O0 backend
    ("O1_ir", "default<O1>", [], []),
    # MIR inlining and the other MIR optimizations rustc enables at O1
    ("mir_opt_2", None, ["-Zmir-opt-level=2"], []),

    # Parts of the O1 backend, without any IR passes. SelectionDAG still runs with the O0 level (fewer DAG combines).
    # The optimized register allocation also brings its pipeline (coalescer, machine scheduler, machine LICM, ...).
    ("isel_dag", None, ["-Cllvm-args=-fast-isel=false"], []),
    ("regalloc_greedy", None, ["-Cllvm-args=-optimize-regalloc", "-Cllvm-args=-regalloc=greedy"], []),
    ("isel_dag_regalloc_greedy", None,
     ["-Cllvm-args=-fast-isel=false", "-Cllvm-args=-optimize-regalloc", "-Cllvm-args=-regalloc=greedy"], []),

    # Single passes
    ("inline", "cgscc(inline)", [], []),
    ("sroa", "function(sroa<modify-cfg>)", [], []),
    ("mem2reg", "function(mem2reg)", [], []),
    ("instcombine", "function(instcombine<max-iterations=1;no-verify-fixpoint>)", [], []),
    ("simplifycfg", "function(simplifycfg)", [], []),
    ("early_cse", "function(early-cse)", [], []),
    ("sccp", "function(sccp)", [], []),
    # LICM only finds something to hoist once SROA turned the allocas into SSA values
    ("sroa_licm", "function(sroa<modify-cfg>,loop-mssa(licm))", [], []),

    # Inlining followed by the simplification of each inlined function, like the inliner pipeline of O1
    ("inline_sroa", "cgscc(inline,function(sroa<modify-cfg>))", [], []),
    ("inline_simplify",
     "cgscc(devirt<4>(inline,function(sroa<modify-cfg>,early-cse,simplifycfg,instcombine<max-iterations=1;no-verify-fixpoint>)))",
     [], []),
]


def write_wrapper(name, passes, flags):
    """Writes a rustc wrapper that appends the flags of the variant, so they override the ones cargo passes."""
    VARIANT_DIR.mkdir(parents=True, exist_ok=True)
    args = [*flags, *([f"-Cpasses={passes}"] if passes else [])]
    wrapper = VARIANT_DIR / f"{name}.sh"
    wrapper.write_text(f"#!/bin/bash\n"
                       f"# {name} (generated by llvm_passes.py)\n\n"
                       f"exec rustc {TOOLCHAIN} \"$@\" {' '.join(shlex.quote(arg) for arg in args)}\n")
    wrapper.chmod(0o755)
    return str(wrapper)


def format_pipeline(pipeline):
    """One pass per line, nested passes indented."""
    lines, current, nesting, params = [], "", 0, 0

    def flush():
        nonlocal current
        if current:
            lines.append("  " * nesting + current)
        current = ""

    for char in pipeline:
        # Parameters like simplifycfg<...> are part of their pass
        if char == "<":
            params += 1
        elif char == ">":
            params -= 1
        if params == 0 and char == "(":
            current += char
            flush()
            nesting += 1
        elif params == 0 and char == ",":
            flush()
        elif params == 0 and char == ")":
            flush()
            nesting -= 1
            current = char
        else:
            current += char
    flush()
    return "\n".join(lines)


def print_pipeline():
    sysroot = run_task("Finding the sysroot", ["rustc", TOOLCHAIN, "--print", "sysroot"])
    opt = Path(sysroot) / "lib/rustlib" / TARGET / "bin/opt"
    if not opt.exists():
        raise SystemExit(f"opt not found: {opt}\nInstall it with: rustup component add llvm-tools {TOOLCHAIN}")
    pipeline = run_task(f"Printing the {PIPELINE_LEVEL} pipeline",
                        [str(opt), f"-passes=default<{PIPELINE_LEVEL}>", "-print-pipeline-passes", "-disable-output",
                         "/dev/null"])
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / f"{PIPELINE_LEVEL}_pipeline.txt"
    path.write_text(pipeline + "\n\n" + format_pipeline(pipeline) + "\n")
    print(format_pipeline(pipeline))
    print(f"\nWritten to {path}")


def results():
    # Skip the databases of benchmarks that did not run yet
    if (DB_DIR / COMPILE_DB).exists():
        compiletime_results(db=COMPILE_DB, suffix=" LLVM passes", baseline=BASELINE, transpose=True)
    if (DB_DIR / RUNTIME_DB).exists():
        runtime_results(db=RUNTIME_DB, suffix=" LLVM passes", baseline=BASELINE, transpose=True)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--rerun", action="store_true",
                        help="Delete the previous results (with --only just the ones of these variants) and rerun")
    parser.add_argument("--only", nargs="*", help="Only run these variants")
    parser.add_argument("--skip-compiletime", action="store_true", help="Do not run the compile time benchmarks")
    parser.add_argument("--skip-runtime", action="store_true", help="Do not run the runtime benchmarks")
    parser.add_argument("--results", action="store_true", help="Only print the results of previous runs")
    parser.add_argument("--print-pipeline", action="store_true",
                        help=f"Only print the passes of the {PIPELINE_LEVEL} pipeline")
    args = parser.parse_args()

    if args.print_pipeline:
        print_pipeline()
        return
    if args.results:
        results()
        return

    unknown = set(args.only or []) - {name for name, *_ in VARIANTS}
    if unknown:
        raise SystemExit(f"Unknown variants: {', '.join(sorted(unknown))}")
    config = [(write_wrapper(name, passes, flags), name, settings)
              for name, passes, flags, settings in VARIANTS if not args.only or name in args.only]

    # Without --only all results are replaced, so the databases can just be removed
    purge = args.rerun and bool(args.only)
    if args.rerun and not args.only:
        run_task("Remove previous results", ["rm", "-f", COMPILE_DB, RUNTIME_DB], cwd=DB_DIR)

    try:
        if not args.skip_compiletime:
            run_compiletime_benchmark(config, db=COMPILE_DB, suffix=" (LLVM passes)", include=COMPILE_BENCHMARKS,
                                      purge=purge, iterations=COMPILE_ITERATIONS)
        if not args.skip_runtime:
            # Purging removes all results of a variant, so only do it with its first group
            for index, (group, benchmarks) in enumerate(RUNTIME_BENCHMARKS.items()):
                run_runtime_benchmark(config, db=RUNTIME_DB, group=group, include=benchmarks,
                                      purge=purge and index == 0,
                                      iterations=RUNTIME_ITERATIONS)
    finally:
        shutil.rmtree(TMP_DIR, ignore_errors=True)

    results()


if __name__ == '__main__':
    main()
